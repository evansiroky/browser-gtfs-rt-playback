#!/usr/bin/env python3
"""Writes src/trips/zone-table.ts: service day starts and agency dates computed from the IANA
database through Python's zoneinfo, a source independent of the Intl code under test.

    python3 server/scripts/zone-table.py > server/src/trips/zone-table.ts && npx prettier --write server/src/trips/zone-table.ts
"""
import datetime as dt
from zoneinfo import ZoneInfo

ZONES = [
    'America/Los_Angeles', 'America/New_York', 'Europe/London', 'Europe/Dublin', 'Asia/Kolkata',
    'Asia/Tehran', 'Australia/Lord_Howe', 'Australia/Sydney', 'Pacific/Auckland',
    'Pacific/Chatham', 'America/St_Johns', 'America/Santiago', 'America/Havana',
    'Antarctica/Troll', 'Pacific/Apia',
]
# Zones whose rules changed lately or are modelled with negative DST (Africa/Casablanca,
# Africa/Cairo, America/Asuncion) are left out: the Intl data of an older Node and the system
# database can disagree about them, and a failure there says nothing about the arithmetic.
UTC = dt.timezone.utc


def transitions(zone):
    tz = ZoneInfo(zone)
    out = []
    t = dt.datetime(2026, 1, 1, tzinfo=UTC)
    prev = t.astimezone(tz).utcoffset()
    end = dt.datetime(2027, 1, 1, tzinfo=UTC)
    while t < end:
        t += dt.timedelta(minutes=15)
        cur = t.astimezone(tz).utcoffset()
        if cur != prev:
            out.append(int(t.timestamp()))
            prev = cur
    return out


def day_start(tz, date):
    noon = dt.datetime(date.year, date.month, date.day, 12, tzinfo=tz)
    return int(noon.timestamp()) - 43200


starts, dates = [], []
for zone in ZONES:
    tz = ZoneInfo(zone)
    days = {dt.date(2026, 1, 15), dt.date(2026, 7, 15)}
    for instant in transitions(zone):
        local = dt.datetime.fromtimestamp(instant, tz).date()
        for delta in (-1, 0, 1):
            days.add(local + dt.timedelta(days=delta))
        for offset in (-1, 0, 3599, 3600):
            dates.append((zone, instant + offset, dt.datetime.fromtimestamp(instant + offset, tz).strftime('%Y%m%d')))
    for day in sorted(days):
        starts.append((zone, day.strftime('%Y%m%d'), day_start(tz, day)))

print('// Generated by server/scripts/zone-table.py from the IANA database (Python zoneinfo); do not edit.')
print('// [zone, service date, epoch seconds of noon minus 12 h]')
print('export const SERVICE_DAY_STARTS: readonly (readonly [string, string, number])[] = [')
for row in starts:
    print(f"  ['{row[0]}', '{row[1]}', {row[2]}],")
print('];')
print()
print('// [zone, epoch seconds around a change of offset, the local calendar date then]')
print('export const AGENCY_DATES: readonly (readonly [string, number, string])[] = [')
for row in dates:
    print(f"  ['{row[0]}', {row[1]}, '{row[2]}'],")
print('];')
